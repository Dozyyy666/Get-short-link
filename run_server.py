import uvicorn

if __name__ == "__main__":
    # Запускаем сервер с параметрами
    uvicorn.run(
        "app.main:app",  # Путь к приложению
        host="127.0.0.1",  # Адрес
        port=8000,  # Порт
        reload=True  # Автоматическая перезагрузка при изменениях
    )


